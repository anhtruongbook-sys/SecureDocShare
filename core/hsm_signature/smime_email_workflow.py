# -*- coding: utf-8 -*-
"""
smime_email_workflow.py: PHÂN HỆ EMAIL KÝ SỐ S/MIME (RFC 8551) & LUỒNG THÔNG BÁO YÊU CẦU / TRẢ KẾT QUẢ KÝ SỐ TỰ ĐỘNG
Dự án: Nghiên cứu Chữ ký số Cá nhân Chuẩn HSM & Tích hợp Krypto (SecureDocShare)

Tính năng kỹ thuật cốt lõi:
1. Tạo và gửi Email Thông báo Yêu cầu Ký số (Signing Request Notification):
   - Khi có văn bản trình ký, tính mã băm SHA-256 nguyên bản, sinh mã phiếu [#REQ-YYYYMMDD-XXXX].
   - Gửi email thông báo tới chủ nhân chữ ký số HSM kèm thông tin người trình, mã băm kiểm chứng và lệnh phê duyệt.
2. Tạo và gửi Email Trả Kết quả Đã Ký số (Signed Document & Audit Receipt Delivery):
   - Nhúng trực tiếp ảnh chữ ký tay (.PNG nền trong suốt) vào thân bức thư HTML.
   - Đính kèm tệp PDF đã ký số chuẩn PAdES-HSM + Biên nhận Kiểm toán Chữ ký số (`Audit_Receipt.json`).
3. Ký số Mật mã lên chính bức Email theo chuẩn Quốc tế S/MIME v4.0 (`RFC 8551` - `multipart/signed`):
   - Băm chuẩn hóa `CRLF` toàn bộ khối nội dung MIME của bức thư (`SHA-256`).
   - Chỉ truyền 32 bytes mã băm vào buồng HSM (`vault.sign_digest_pkcs11()`) để sinh tệp chữ ký số `smime.p7s` (`application/pkcs7-signature`).
   - Xuất ra tệp `.eml` chuẩn quốc tế (mở trực tiếp trên Microsoft Outlook, Apple Mail, Thunderbird hiển thị huy hiệu Chữ ký số hợp lệ)
     và hỗ trợ gửi trực tiếp qua máy chủ SMTP/TLS (Gmail, Microsoft 365, Mail doanh nghiệp).
"""

import os
import json
import uuid
import base64
import hashlib
import smtplib
import datetime
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.mime.application import MIMEApplication
from email.mime.image import MIMEImage
from email.utils import formatdate, make_msgid
from typing import Dict, Any, Optional, List, Tuple

from .hsm_pkcs11_ca_vault import KryptoHSMVault
from .pdf_pades_hsm_signer import PDFPAdESHSMSigner


class SMIMEEmailWorkflowEngine:
    """Động cơ quản lý Yêu cầu Ký số qua Email và Ký số bức thư trả kết quả chuẩn S/MIME (RFC 8551)."""

    @staticmethod
    def _canonicalize_crlf(raw_mime_bytes: bytes) -> bytes:
        """Chuẩn hóa xuống dòng CRLF theo bắt buộc của RFC 8551 S/MIME trước khi băm SHA-256."""
        normalized = raw_mime_bytes.replace(b"\r\n", b"\n").replace(b"\r", b"\n")
        return normalized.replace(b"\n", b"\r\n")

    @classmethod
    def sign_mime_entity_with_hsm(
        cls,
        inner_mime_part,
        vault: KryptoHSMVault,
        user_pin: str,
        totp_code: Optional[str] = None,
        subject: str = "[Krypto HSM] Thông báo Ký số",
        from_addr: str = "",
        to_addrs: List[str] = None,
        cc_addrs: Optional[List[str]] = None
    ) -> Tuple[bytes, Dict[str, Any]]:
        """
        Bọc một thực thể MIME vào khung `multipart/signed; protocol="application/pkcs7-signature"; micalg=sha-256`
        và ký bằng khóa bí mật bên trong HSM (sinh phần đính kèm `smime.p7s`).
        """
        creds = vault.get_public_credentials_and_png()
        sender_email = from_addr or f"{creds['signer_name']} <{creds['signer_email']}>"
        recipients = to_addrs or [creds["signer_email"]]

        # Bước 1: Kết xuất phần thân MIME bên trong và chuẩn hóa CRLF để tính mã băm SHA-256
        inner_raw_bytes = inner_mime_part.as_bytes()
        inner_crlf = cls._canonicalize_crlf(inner_raw_bytes)
        mime_sha256_digest = hashlib.sha256(inner_crlf).digest()

        # Bước 2: Gửi đúng 32 bytes mã băm của bức thư vào buồng HSM để tạo cấu trúc PKCS#7 (smime.p7s)
        cms_der, hsm_sig_res = PDFPAdESHSMSigner.build_cms_signed_data_via_hsm(
            byterange_sha256_digest=mime_sha256_digest,
            vault=vault,
            user_pin=user_pin,
            totp_code=totp_code,
            document_label=f"S/MIME Email: {subject}",
            content_type_str="data",
        )

        # Bước 3: Lắp ráp gói multipart/signed theo đúng cấu trúc byte RFC 8551
        boundary = f"----=_KryptoSMIME_{uuid.uuid4().hex}"
        msg_id = make_msgid(domain=creds["signer_email"].split("@")[-1] if "@" in creds["signer_email"] else "krypto.local")
        date_hdr = formatdate(localtime=True)

        headers = [
            f"MIME-Version: 1.0",
            f"Date: {date_hdr}",
            f"Message-ID: {msg_id}",
            f"Subject: {subject}",
            f"From: {sender_email}",
            f"To: {', '.join(recipients)}",
        ]
        if cc_addrs:
            headers.append(f"Cc: {', '.join(cc_addrs)}")
        headers.extend([
            f"X-Mailer: Krypto PQC-HSM Personal Digital Signature Suite",
            f"X-Krypto-HSM-Serial: {creds['serial_hex']}",
            f'Content-Type: multipart/signed; protocol="application/pkcs7-signature"; micalg=sha-256; boundary="{boundary}"',
            "",
            "This is a cryptographically signed S/MIME message generated by Krypto HSM.",
            f"--{boundary}",
        ])

        p7s_b64_lines = base64.encodebytes(cms_der).decode("ascii").strip().splitlines()
        p7s_part = [
            f"--{boundary}",
            'Content-Type: application/pkcs7-signature; name="smime.p7s"',
            "Content-Transfer-Encoding: base64",
            'Content-Disposition: attachment; filename="smime.p7s"',
            "Content-Description: S/MIME Cryptographic Signature (HSM PKCS#11)",
            "",
            *p7s_b64_lines,
            f"--{boundary}--",
            "",
        ]

        full_eml_bytes = (
            "\r\n".join(headers).encode("utf-8")
            + b"\r\n"
            + inner_crlf
            + b"\r\n"
            + "\r\n".join(p7s_part).encode("ascii")
        )

        return full_eml_bytes, {
            "message_id": msg_id,
            "subject": subject,
            "from": sender_email,
            "to": recipients,
            "mime_body_sha256": mime_sha256_digest.hex(),
            "smime_p7s_size": len(cms_der),
            "hsm_audit_receipt": hsm_sig_res["audit_receipt"],
        }

    @classmethod
    def create_signing_request_email(
        cls,
        document_path: str,
        requester_name: str,
        requester_email: str,
        signing_reason: str,
        vault: KryptoHSMVault,
        user_pin: str,
        output_eml_path: str,
        totp_code: Optional[str] = None,
        smtp_config: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        Tạo và gửi Email Thông báo Yêu cầu Ký số (`[YÊU CẦU KÝ SỐ #REQ-...]`) tới email của chủ nhân chữ ký số.
        """
        creds = vault.get_public_credentials_and_png()
        with open(document_path, "rb") as f:
            doc_bytes = f.read()
        doc_sha256 = hashlib.sha256(doc_bytes).hexdigest()
        doc_name = os.path.basename(document_path)
        now_vn = datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=7)))
        req_id = f"REQ-{now_vn.strftime('%Y%m%d')}-{doc_sha256[:6].upper()}"

        html_body = f"""<!DOCTYPE html>
<html lang="vi">
<head><meta charset="utf-8"></head>
<body style="font-family: 'Segoe UI', Arial, sans-serif; color: #0f172a; line-height: 1.55;">
  <div style="max-width: 640px; margin: 0 auto; border: 1px solid #cbd5e1; border-radius: 10px; overflow: hidden;">
    <div style="background: #003399; color: #ffffff; padding: 16px 20px;">
      <h2 style="margin: 0; font-size: 18px;">[KRYPTO HSM] YÊU CẦU PHÊ DUYỆT &amp; KÝ SỐ TÀI LIỆU</h2>
      <p style="margin: 4px 0 0; font-size: 13px; opacity: 0.9;">Mã yêu cầu: <strong>{req_id}</strong> • Thời gian: {now_vn.strftime('%d/%m/%Y %H:%M:%S +07:00')}</p>
    </div>
    <div style="padding: 20px;">
      <p>Kính gửi <strong>{creds['signer_name']}</strong> (<em>{creds['signer_title']} — {creds['organization']}</em>),</p>
      <p>Hệ thống vừa tiếp nhận một yêu cầu ký số chuẩn <strong>PAdES-HSM</strong> gắn chữ ký tay cá nhân của bạn với thông tin chi tiết như sau:</p>
      <table style="width: 100%; border-collapse: collapse; margin: 14px 0; font-size: 14px;">
        <tr><td style="padding: 8px; border: 1px solid #e2e8f0; background: #f8fafc; width: 34%;"><strong>Tệp tài liệu cần ký:</strong></td><td style="padding: 8px; border: 1px solid #e2e8f0;"><strong>{doc_name}</strong> ({len(doc_bytes)/1024:.1f} KB)</td></tr>
        <tr><td style="padding: 8px; border: 1px solid #e2e8f0; background: #f8fafc;"><strong>Người trình ký:</strong></td><td style="padding: 8px; border: 1px solid #e2e8f0;">{requester_name} ({requester_email})</td></tr>
        <tr><td style="padding: 8px; border: 1px solid #e2e8f0; background: #f8fafc;"><strong>Nội dung / Lý do ký:</strong></td><td style="padding: 8px; border: 1px solid #e2e8f0;">{signing_reason}</td></tr>
        <tr><td style="padding: 8px; border: 1px solid #e2e8f0; background: #f8fafc;"><strong>Mã băm SHA-256 gốc:</strong></td><td style="padding: 8px; border: 1px solid #e2e8f0; font-family: monospace; font-size: 12px; word-break: break-all;">{doc_sha256}</td></tr>
        <tr><td style="padding: 8px; border: 1px solid #e2e8f0; background: #f8fafc;"><strong>Buồng HSM đích:</strong></td><td style="padding: 8px; border: 1px solid #e2e8f0;">Slot <code>{creds['slot_id']}</code> (Serial: <code>{creds['serial_hex'][:16]}</code>)</td></tr>
      </table>
      <p style="font-size: 13px; color: #334155;">Vui lòng mở ứng dụng <strong>Krypto</strong> trên Điện thoại hoặc PC, kiểm tra mã băm SHA-256 và xác thực bằng <strong>USER_PIN + Vân tay / Mã OTP 6 số</strong> để thực hiện lệnh ký <code>PKCS#11 C_Sign</code>.</p>
    </div>
  </div>
</body>
</html>"""

        inner_part = MIMEMultipart("mixed")
        inner_part.attach(MIMEText(html_body, "html", "utf-8"))

        subject = f"[YÊU CẦU KÝ SỐ #{req_id}] {doc_name} - Trình bởi: {requester_name}"
        eml_bytes, meta = cls.sign_mime_entity_with_hsm(
            inner_mime_part=inner_part,
            vault=vault,
            user_pin=user_pin,
            totp_code=totp_code,
            subject=subject,
            to_addrs=[creds["signer_email"]],
            cc_addrs=[requester_email] if requester_email and requester_email != creds["signer_email"] else None,
        )

        os.makedirs(os.path.dirname(os.path.abspath(output_eml_path)), exist_ok=True)
        with open(output_eml_path, "wb") as f_out:
            f_out.write(eml_bytes)

        smtp_sent = False
        if smtp_config and smtp_config.get("host"):
            smtp_sent = cls._send_via_smtp(eml_bytes, creds["signer_email"], [creds["signer_email"]], smtp_config)

        return {
            "request_id": req_id,
            "document_name": doc_name,
            "document_sha256": doc_sha256,
            "output_eml_path": output_eml_path,
            "smtp_sent": smtp_sent,
            "smime_metadata": meta,
        }

    @classmethod
    def create_signed_result_delivery_email(
        cls,
        signing_result: Dict[str, Any],
        vault: KryptoHSMVault,
        user_pin: str,
        output_eml_path: str,
        totp_code: Optional[str] = None,
        recipient_emails: Optional[List[str]] = None,
        smtp_config: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        Tạo và gửi Email Trả Kết quả Đã Ký số (`[ĐÃ KÝ SỐ HOÀN TẤT - PAdES & S/MIME]`):
        - Hiển thị trực tiếp ảnh chữ ký tay (.PNG) trong nội dung HTML (`cid:handwritten_sig_png`).
        - Đính kèm tệp PDF đã ký số chuẩn PAdES-HSM.
        - Đính kèm Biên nhận Kiểm toán Chữ ký số (`Audit_Receipt.json`).
        - Ký số toàn bộ bức thư bằng chuẩn `S/MIME (smime.p7s)`.
        """
        creds = vault.get_public_credentials_and_png()
        signed_pdf_path = signing_result["output_pdf_path"]
        signed_pdf_name = os.path.basename(signed_pdf_path)

        with open(signed_pdf_path, "rb") as f_pdf:
            signed_pdf_bytes = f_pdf.read()

        audit_receipt_bytes = json.dumps({
            "receipt_type": "KRYPTO_PADES_HSM_AUDIT_RECEIPT",
            "signer_name": creds["signer_name"],
            "signer_email": creds["signer_email"],
            "signer_title": creds["signer_title"],
            "organization": creds["organization"],
            "certificate_serial_hex": creds["serial_hex"],
            "root_ca_serial_hex": creds["root_serial_hex"],
            "visual_signature_png_sha256": creds["visual_sig_png_sha256"],
            "original_document_sha256": signing_result["original_sha256"],
            "signed_pdf_sha256": signing_result["signed_pdf_sha256"],
            "byterange_digest_hex": signing_result["byterange_digest_hex"],
            "signing_time_local": signing_result["signing_time_local"],
            "hsm_audit_chain_entry": signing_result["hsm_audit_receipt"],
        }, ensure_ascii=False, indent=2).encode("utf-8")

        html_body = f"""<!DOCTYPE html>
<html lang="vi">
<head><meta charset="utf-8"></head>
<body style="font-family: 'Segoe UI', Arial, sans-serif; color: #0f172a; line-height: 1.55;">
  <div style="max-width: 660px; margin: 0 auto; border: 1px solid #cbd5e1; border-radius: 10px; overflow: hidden;">
    <div style="background: #059669; color: #ffffff; padding: 16px 20px;">
      <h2 style="margin: 0; font-size: 18px;">✓ HOÀN TẤT KÝ SỐ TÀI LIỆU (CHUẨN PAdES-HSM &amp; S/MIME)</h2>
      <p style="margin: 4px 0 0; font-size: 13px; opacity: 0.95;">Tệp đính kèm: <strong>{signed_pdf_name}</strong> • Thời gian ký: {signing_result['signing_time_local']}</p>
    </div>
    <div style="padding: 20px;">
      <p>Xin thông báo tài liệu đã được ký số thành công bởi Buồng bảo mật phần cứng <strong>Krypto PKCS#11 HSM</strong> và được xác thực toàn vẹn:</p>
      <table style="width: 100%; border-collapse: collapse; margin: 14px 0; font-size: 13.5px;">
        <tr><td style="padding: 8px; border: 1px solid #e2e8f0; background: #f8fafc; width: 35%;"><strong>Người ký số:</strong></td><td style="padding: 8px; border: 1px solid #e2e8f0;"><strong>{creds['signer_name']}</strong> ({creds['signer_title']} — {creds['organization']})</td></tr>
        <tr><td style="padding: 8px; border: 1px solid #e2e8f0; background: #f8fafc;"><strong>Email định danh S/MIME:</strong></td><td style="padding: 8px; border: 1px solid #e2e8f0;">{creds['signer_email']}</td></tr>
        <tr><td style="padding: 8px; border: 1px solid #e2e8f0; background: #f8fafc;"><strong>Số Serial Chứng thư HSM:</strong></td><td style="padding: 8px; border: 1px solid #e2e8f0; font-family: monospace;">{creds['serial_hex']}</td></tr>
        <tr><td style="padding: 8px; border: 1px solid #e2e8f0; background: #f8fafc;"><strong>SHA-256 Ảnh chữ ký tay:</strong></td><td style="padding: 8px; border: 1px solid #e2e8f0; font-family: monospace; font-size: 12px; word-break: break-all;">{creds['visual_sig_png_sha256']}</td></tr>
        <tr><td style="padding: 8px; border: 1px solid #e2e8f0; background: #f8fafc;"><strong>SHA-256 Tệp PDF đã ký:</strong></td><td style="padding: 8px; border: 1px solid #e2e8f0; font-family: monospace; font-size: 12px; word-break: break-all;">{signing_result['signed_pdf_sha256']}</td></tr>
        <tr><td style="padding: 8px; border: 1px solid #e2e8f0; background: #f8fafc;"><strong>Mã kiểm toán HSM (Audit):</strong></td><td style="padding: 8px; border: 1px solid #e2e8f0; font-family: monospace; font-size: 12px;">Seq #{signing_result['hsm_audit_receipt']['seq']} | {signing_result['hsm_audit_receipt']['entry_hash'][:24]}...</td></tr>
      </table>
      <div style="border: 1px dashed #003399; background: #f8fafc; border-radius: 8px; padding: 12px 16px; margin-top: 14px; text-align: center;">
        <div style="font-size: 12px; color: #475569; margin-bottom: 6px;">Mẫu Chữ Ký Tay Gắn Kết Toán Học Trong HSM (<code>CKO_DATA</code>):</div>
        <img src="cid:handwritten_sig_png" alt="Chữ ký tay" style="max-height: 90px; width: auto;" />
        <div style="font-weight: bold; color: #003399; margin-top: 4px;">{creds['signer_name']}</div>
      </div>
    </div>
  </div>
</body>
</html>"""

        root_mixed = MIMEMultipart("mixed")
        related_part = MIMEMultipart("related")
        related_part.attach(MIMEText(html_body, "html", "utf-8"))

        # Nhúng ảnh chữ ký tay .PNG inline (cid:handwritten_sig_png)
        img_part = MIMEImage(creds["handwritten_png_bytes"], _subtype="png")
        img_part.add_header("Content-ID", "<handwritten_sig_png>")
        img_part.add_header("Content-Disposition", 'inline; filename="handwritten_signature.png"')
        related_part.attach(img_part)
        root_mixed.attach(related_part)

        # Đính kèm tệp PDF đã ký số PAdES
        pdf_att = MIMEApplication(signed_pdf_bytes, _subtype="pdf")
        pdf_att.add_header("Content-Disposition", f'attachment; filename="{signed_pdf_name}"')
        root_mixed.attach(pdf_att)

        # Đính kèm biên nhận kiểm toán JSON
        receipt_att = MIMEApplication(audit_receipt_bytes, _subtype="json")
        receipt_att.add_header("Content-Disposition", 'attachment; filename="Krypto_HSM_Audit_Receipt.json"')
        root_mixed.attach(receipt_att)

        targets = recipient_emails or [creds["signer_email"]]
        subject = f"[KẾT QUẢ KÝ SỐ HSM] {signed_pdf_name} - Ký bởi: {creds['signer_name']}"

        eml_bytes, meta = cls.sign_mime_entity_with_hsm(
            inner_mime_part=root_mixed,
            vault=vault,
            user_pin=user_pin,
            totp_code=totp_code,
            subject=subject,
            to_addrs=targets,
        )

        os.makedirs(os.path.dirname(os.path.abspath(output_eml_path)), exist_ok=True)
        with open(output_eml_path, "wb") as f_out:
            f_out.write(eml_bytes)

        smtp_sent = False
        if smtp_config and smtp_config.get("host"):
            smtp_sent = cls._send_via_smtp(eml_bytes, creds["signer_email"], targets, smtp_config)

        return {
            "output_eml_path": output_eml_path,
            "eml_size_bytes": len(eml_bytes),
            "attached_signed_pdf": signed_pdf_path,
            "smtp_sent": smtp_sent,
            "smime_metadata": meta,
        }

    @staticmethod
    def _send_via_smtp(
        raw_eml_bytes: bytes,
        sender_email: str,
        recipient_emails: List[str],
        smtp_config: Dict[str, Any]
    ) -> bool:
        """Gửi bức thư đã ký số S/MIME qua máy chủ SMTP/TLS thực tế (Gmail, Outlook/M365, Custom SMTP)."""
        host = smtp_config["host"]
        port = int(smtp_config.get("port", 587))
        username = smtp_config.get("username", sender_email)
        password = smtp_config.get("password", "")
        use_tls = smtp_config.get("use_tls", True)

        with smtplib.SMTP(host, port, timeout=20) as server:
            if use_tls:
                server.starttls()
            if username and password:
                server.login(username, password)
            server.sendmail(sender_email, recipient_emails, raw_eml_bytes)
        return True
